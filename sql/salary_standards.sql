-- ============================================================
-- salary_standards — 인건비·기본경비 편성 기준값
--
-- 왜 테이블로 빼는가:
--   기준값을 index.html에 하드코딩해 두면 규정이 개정될 때 코드를 고쳐야 하고,
--   실제로 그래서 정액급식비가 140,000원(구 조문)으로 남아 있었다.
--   조문·단가·산식을 데이터로 두면 규정 개정 시 이 표만 갱신하면 된다.
--
-- 채우는 규칙:
--   amount  정액(원). 요율 항목은 null
--   rate    요율(%). 정액 항목은 null
--   unit    amount/rate가 적용되는 단위 (월 / 연 / 시간 / 일 / 월봉급액×2회)
--   formula 산식 템플릿 — 편성 계산기가 그대로 쓴다
--   basis   기관 자체 규정 조문 (1차 근거)
--   source  준용하는 상위 법령·지침 (2차 근거)
--   note    편성·심사 시 걸리는 지점
--
-- 여기 들어가는 것은 "기준"뿐이다. 직급별 인원·편성액 같은 실적 데이터는
-- budget_items에 있으므로 이 표에 넣지 않는다.
-- ============================================================

create table if not exists salary_standards (
  id bigint generated always as identity primary key,
  institution_id bigint not null,
  year int not null default 2027,
  category text not null,   -- 기본급 / 수당 / 법정부담금 / 퇴직급여 / 평가급 / 복리후생 / 기본경비
  item text not null,       -- 정액급식비 / 직급보조비 / 정근수당 …
  grade text,               -- 전직급 / 일반직 3급 / 근속 5년미만 …
  amount numeric,
  rate numeric,
  unit text,
  formula text,
  basis text,
  source text,
  note text,
  sort_order int default 0
);

create index if not exists idx_salary_standards_lookup
  on salary_standards (institution_id, year, category, sort_order);

comment on table salary_standards is '인건비·기본경비 편성 기준값. 규정 개정 시 코드가 아니라 이 표만 고친다.';

